SELECT P.ID, P.NAME, P.HOST_ID
FROM PLACES P
WHERE EXISTS (
    SELECT 1
    FROM PLACES PP
    WHERE P.HOST_ID = PP.HOST_ID
    GROUP BY PP.HOST_ID
    HAVING COUNT(*) >= 2
)
ORDER BY P.ID


