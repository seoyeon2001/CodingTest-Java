WITH RECURSIVE CTE1 AS (
    SELECT 1 AS ID
    UNION ALL
    SELECT ID + 1
    FROM CTE1
    WHERE ID < (SELECT MAX(ID) FROM ECOLI_DATA)   
), CTE2 AS (
    SELECT PARENT_ID, COUNT(PARENT_ID) AS CHILD_COUNT
    FROM ECOLI_DATA
    WHERE PARENT_ID IS NOT NULL
    GROUP BY PARENT_ID
)

SELECT C1.ID, IFNULL(C2.CHILD_COUNT, 0) AS CHILD_COUNT
FROM CTE1 C1
LEFT JOIN CTE2 C2 ON C1.ID = C2.PARENT_ID
ORDER BY ID