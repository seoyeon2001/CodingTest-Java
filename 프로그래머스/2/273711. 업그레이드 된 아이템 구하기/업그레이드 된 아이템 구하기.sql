WITH CTE AS (
    SELECT C.ITEM_ID
    FROM ITEM_INFO P
    JOIN ITEM_TREE C ON P.ITEM_ID = C.PARENT_ITEM_ID
    WHERE RARITY = 'RARE'
)

SELECT I.ITEM_ID, ITEM_NAME, RARITY
FROM ITEM_INFO I
JOIN CTE C ON I.ITEM_ID = C.ITEM_ID
ORDER BY I.ITEM_ID DESC

