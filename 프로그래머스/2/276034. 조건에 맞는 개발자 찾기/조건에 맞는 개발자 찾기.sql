SELECT ID, EMAIL, FIRST_NAME, LAST_NAME
FROM DEVELOPERS
JOIN SKILLCODES
WHERE NAME IN ('Python' ,'C#') AND SKILL_CODE & CODE = CODE
GROUP BY ID
ORDER BY ID

